/**
 * Google Sign-In. Requires Firebase configuration (google-services.json +
 * a web client ID generated by the Google services plugin, exposed as the
 * `default_web_client_id` string). When absent, a clear message is shown
 * instead of a decorative button.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun GoogleSignInScreen(
    onBack: () -> Unit,
    onSignedIn: () -> Unit,
    viewModel: AuthViewModel = hiltViewModel()
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val snackbarHostState = remember { SnackbarHostState() }
    val loading by viewModel.loading.collectAsStateWithLifecycle()

    val webClientId = remember {
        val id = context.resources.getIdentifier(
            "default_web_client_id", "string", context.packageName
        )
        if (id != 0) context.getString(id) else null
    }

    val signInLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.StartActivityForResult()
    ) { result ->
        val task = GoogleSignIn.getSignedInAccountFromIntent(result.data)
        try {
            val account = task.getResult(Exception::class.java)
            val idToken = account?.idToken
            if (idToken != null) {
                viewModel.signInWithGoogleIdToken(idToken)
            } else {
                scope.launch {
                    snackbarHostState.showSnackbar(
                        context.getString(R.string.google_signin_failed)
                    )
                }
            }
        } catch (e: Exception) {
            scope.launch {
                snackbarHostState.showSnackbar(
                    context.getString(R.string.google_signin_failed)
                )
            }
        }
    }

    LaunchedEffect(Unit) {
        viewModel.events.collect { event ->
            when (event) {
                AuthEvent.Success -> onSignedIn()
                is AuthEvent.Error -> {
                    val base = context.getString(authErrorMessage(event.code))
                    snackbarHostState.showSnackbar(
                        if (event.code == com.maakthi.prescriptionpharmacist.core.auth.AuthErrorType.UNKNOWN) {
                            event.detail?.let { "$base — $it" } ?: base
                        } else {
                            base
                        }
                    )
                }
                AuthEvent.VerificationEmailSent ->
                    snackbarHostState.showSnackbar(context.getString(R.string.auth_verification_sent))
                AuthEvent.PasswordResetSent ->
                    snackbarHostState.showSnackbar(context.getString(R.string.auth_reset_sent))
                AuthEvent.AccountDeleted -> onSignedIn()
            }
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.google_signin_title)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = stringResource(R.string.back)
                        )
                    }
                }
            )
        },
        snackbarHost = { SnackbarHost(snackbarHostState) }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            Icon(
                imageVector = Icons.Filled.AccountCircle,
                contentDescription = null,
                tint = MaterialTheme.colorScheme.primary,
                modifier = Modifier.size(96.dp)
            )
            Spacer(Modifier.height(20.dp))
            Text(
                text = stringResource(R.string.google_signin_subtitle),
                style = MaterialTheme.typography.bodyLarge,
                textAlign = TextAlign.Center,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
            Spacer(Modifier.height(24.dp))

            if (viewModel.firebaseAvailable && webClientId != null) {
                Button(
                    onClick = {
                        val options = GoogleSignInOptions.Builder(
                            GoogleSignInOptions.DEFAULT_SIGN_IN
                        )
                            .requestIdToken(webClientId)
                            .requestEmail()
                            .build()
                        signInLauncher.launch(
                            GoogleSignIn.getClient(context, options).signInIntent
                        )
                    },
                    enabled = !loading,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    if (loading) {
                        CircularProgressIndicator(color = MaterialTheme.colorScheme.onPrimary)
                    } else {
                        Text(stringResource(R.string.google_signin_button))
                    }
                }
            } else {
                FeatureNotReadyCard(message = stringResource(R.string.google_signin_not_ready))
            }
        }
    }
}
